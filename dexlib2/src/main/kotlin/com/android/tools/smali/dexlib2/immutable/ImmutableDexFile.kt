package com.android.tools.smali.dexlib2.immutable

import com.android.tools.smali.dexlib2.Opcodes
import com.android.tools.smali.dexlib2.iface.ClassDef
import com.android.tools.smali.dexlib2.iface.DexFile
import com.android.tools.smali.util.ImmutableUtils

open class ImmutableDexFile(
    override val opcodes: Opcodes,
    classes: Set<ImmutableClassDef>?
) : DexFile {
    override val classes: Set<ImmutableClassDef> = ImmutableUtils.nullToEmptySet(classes)

    constructor(opcodes: Opcodes, classes: Collection<ClassDef>?) :
        this(opcodes, ImmutableClassDef.immutableSetOf(classes))

    companion object {
        fun of(dexFile: DexFile): ImmutableDexFile {
            if (dexFile is ImmutableDexFile) {
                return dexFile
            }
            return ImmutableDexFile(dexFile.opcodes, dexFile.classes)
        }
    }
}
